#!/usr/bin/env python3
"""Build seed/<lang>.sql from seed/strings.json. Run: python3 seed/make-sql.py (from this folder or anywhere)."""
import json, pathlib

here = pathlib.Path(__file__).resolve().parent
data = json.loads((here / "strings.json").read_text(encoding="utf-8"))
q = lambda s: "'" + s.replace("'", "''") + "'"

# Rows the dev drawer "Reload mocks" does not own: the cold-boot seed rows (uuid ids) and the
# shared-in demo project mock-prog-13 (shown first in Programmes, absent from the shipped sets).
CLEANUP = """\
CREATE TEMP TABLE drop_prog AS SELECT id FROM programmes WHERE id NOT LIKE 'mock-%' OR id = 'mock-prog-13';
DELETE FROM programme_photos WHERE programme_id IN (SELECT id FROM drop_prog);
DELETE FROM programme_audio_notes WHERE programme_id IN (SELECT id FROM drop_prog);
DELETE FROM programme_text_notes WHERE programme_id IN (SELECT id FROM drop_prog);
DELETE FROM programme_file_attachments WHERE programme_id IN (SELECT id FROM drop_prog);
DELETE FROM programme_measurements WHERE programme_id IN (SELECT id FROM drop_prog);
DELETE FROM appointments WHERE id NOT LIKE 'mock-%' OR programme_id IN (SELECT id FROM drop_prog);
DELETE FROM programmes WHERE id IN (SELECT id FROM drop_prog);
DROP TABLE drop_prog;
"""

for lang in ("fr", "en", "pcm", "hi", "ar"):
    out = ["-- Generated by make-sql.py from strings.json; do not edit.", "BEGIN;", CLEANUP]
    for i, v in data["programmes.title"].items():
        out.append(f"UPDATE programmes SET title = {q(v[lang])} WHERE id = {q(i)};")
    for i, v in data["programme_text_notes.text"].items():
        out.append(f"UPDATE programme_text_notes SET text = {q('<html>' + v[lang] + '</html>')} WHERE id = {q(i)};")
    for i, v in data["measurement_labels"].items():
        table = "programme_measurements" if i.startswith("mock-pm-") else "measurements"
        out.append(f"UPDATE {table} SET label = {q(v[lang])} WHERE id = {q(i)};")
    for i, v in data["album_groups.name"].items():
        out.append(f"UPDATE album_groups SET name = {q(v[lang])} WHERE id = {q(i)};")
    for i, v in data["contacts"].items():
        out.append(f"UPDATE contacts SET first_name = {q(v['first_name'][lang])}, last_name = {q(v['last_name'][lang])} WHERE id = {q(i)};")
    out.append("COMMIT;")
    (here / f"{lang}.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{lang}.sql", len(out) - 3, "statements")
